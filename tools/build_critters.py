def build_hedgehog(): # ハリネズミ：トゲの背中＋小さな顔
    clear()
    SPIKE=(0.36,0.29,0.22); SPK2=(0.24,0.19,0.14); FACE=(0.86,0.79,0.68); NOSE=(0.16,0.12,0.12)
    E(0.0,0.16,-0.02,0.21,0.17,0.21,SPIKE,ring=12)         # トゲのドーム（土台）
    # トゲ：ドーム上面に放射状の細い円錐を多数
    import random as _r; _r.seed(7)
    for i in range(46):
        a=_r.random()*math.pi*2; rad=_r.random()**0.5*0.19
        bx=math.cos(a)*rad; bz=math.sin(a)*rad - 0.04
        by=0.18+math.sqrt(max(0.0,0.20**2-rad*rad))*0.7
        rotz=-bx*2.4; rotx=bz*2.4
        E(bx,by+0.05,bz,0.018,0.075,0.018,SPIKE if (i%3) else SPK2,seg=6,ring=5,rotX=rotx,rotZ=rotz)
    E(0.0,0.10,0.20,0.085,0.075,0.10,FACE,ring=9)          # 顔（前下・トゲ無し）
    E(0.0,0.085,0.285,0.045,0.040,0.05,FACE,ring=8)        # マズル
    E(0.0,0.085,0.325,0.022,0.020,0.020,NOSE,seg=8,ring=6) # 鼻
    eyes(0.135,0.255,sx=0.05,r=0.024,col=(0.05,0.04,0.05))
    for s in (-1,1): E(s*0.10,0.045,0.16,0.03,0.035,0.04,FACE,seg=8,ring=6) # 前足
    floor0()

