def build_snake():    # 蛇：連続した胴（背骨カーブに沿って滑らかに細るチューブ）＋持ち上げた頭＋舌
    clear()
    SK=(0.30,0.54,0.28); SK2=(0.25,0.47,0.24); BEL=(0.80,0.82,0.55)  # SK2は薄い帯＝鱗ヒント
    N=30
    spine=[]
    for i in range(N):
        t=i/(N-1)
        z=-0.44+t*0.84
        x=math.sin(t*math.pi*2.2)*0.13
        y=0.075+(t**2.6)*0.17                       # 前(頭側)ほど持ち上がる
        r=0.092*(1.0-0.55*abs(t-0.45)/0.55)         # 中央太・両端細の滑らかなテーパ
        col=SK if (i//2)%2==0 else SK2              # 2節ごとの薄い帯（鱗のヒント）
        spine.append((x,y,z,r,col))
    tube(spine, seg=12, ring=8, rzmul=2.0, fur=0.004, sub=1)  # 30点で既に密・rz長めで連続チューブ
    # 背のダイヤ柄（鱗パターン）＝濃色の平たい菱形を背骨上に等間隔
    DIA=(0.17,0.33,0.16)
    for i in range(2, N-3, 3):
        x,y,z,r,_=spine[i]
        E(x, y+r*0.52, z, r*0.45, r*0.26, r*0.85, DIA, seg=8, ring=6)
    xh=math.sin(1.0*math.pi*2.2)*0.13
    E(xh,0.240,0.39,0.082,0.060,0.075,SK,ring=11,fur=0.004)  # 首ブリッジ（胴→頭を滑らかに）
    E(xh,0.252,0.45,0.078,0.052,0.10,SK,ring=12,fur=0.004)   # 頭（平たい菱形・滑らか）
    E(xh,0.228,0.52,0.05,0.035,0.06,BEL,ring=9)              # 顎下の白
    eyes(0.280,0.49,sx=0.046,r=0.024,col=(0.95,0.85,0.15),emis=(0.4,0.35,0.05))  # 黄の目
    for s in (-1,1):                                          # 牙のヒント（小さな白い下向き）
        E(xh+s*0.020,0.206,0.560,0.006,0.020,0.007,(0.98,0.98,0.94),seg=6,ring=5,rotX=0.45)
    ck.whisker((xh,0.220,0.565),(xh-0.03,0.205,0.665),0.006,(0.85,0.10,0.12))    # 舌（二又・チロチロ）
    ck.whisker((xh,0.220,0.565),(xh+0.03,0.205,0.665),0.006,(0.85,0.10,0.12))
    floor0()

