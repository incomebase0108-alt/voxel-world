E = ck.ellipsoid
def clear(): ck.PARTS.clear()
def floor0():
    miny = min(v[1] for p in ck.PARTS for v in p['verts'])
    for p in ck.PARTS:
        p['verts'] = [(x, y - miny, z) for (x, y, z) in p['verts']]

def eyes(y, z, sx=0.06, r=0.03, col=(0.05,0.04,0.05), emis=None, hi=True):
    for s in (-1, 1):
        E(s*sx, y, z, r, r*1.05, r*0.85, col, seg=12, ring=8, rough=0.2, emis=emis)
        if hi:
            E(s*(sx-0.012), y+0.012, z+0.02, r*0.30, r*0.30, r*0.22, (1,1,1), seg=6, ring=5, rough=0.05, emis=(0.8,0.8,0.8))

# ----------------------------------------------------------------------
# 再利用ヘルパー（balloon＝玉の寄せ集め感の根絶用）
#   tube : 背骨カーブに沿って太さが滑らかに変わる連続胴（区間を細分し深く重ねる）
#   limb : 関節＋肉球付きの滑らかな脚を1呼びで生成（centerlineを細分し段差を消す）
# ----------------------------------------------------------------------
def _subdiv(pts, sub):
    """pts=[(x,y,z,r,[col]),...] を各区間 sub 分割して線形補間（色は近い端点を採用）。"""
    out = []
    for i in range(len(pts)-1):
        a, b = pts[i], pts[i+1]
        for k in range(sub):
            t = k/sub
            xyzr = tuple(a[j]+(b[j]-a[j])*t for j in range(4))
            if len(a) >= 5:
                out.append(xyzr + ((a[4] if t < 0.5 else b[4]),))
            else:
                out.append(xyzr)
    out.append(pts[-1])
    return out

def tube(spine, seg=11, ring=8, rzmul=1.45, fur=0.0, sub=2):
    """spine=[(x,y,z,r,col),...] を細分＋深い重ねで連続面の胴に。
       重なり合うブロブなので1球の分割は低めでOK（スムーズ法線＋AOで継ぎ目は出ない）。"""
    for p in _subdiv(spine, sub):
        x, y, z, r, col = p
        E(x, y, z, r, r, r*rzmul, col, seg=seg, ring=ring, fur=fur)

def limb(joints, col, paw=None, pawcol=None, sub=5, rymul=1.7, seg=10, ring=6, fur=0.0):
    """joints=[(x,y,z,r),...] を top→bottom に細分した重ね球で『関節段差の無い脚』に。
       脚は縦(y)に伸びるので各球を ry 方向へ伸ばして縦の重なりを連続させる（リブ防止）。
       paw=(dy,dz,rx,ry,rz) で末端に肉球（前向き接地）。"""
    for (x, y, z, r) in _subdiv(joints, sub):
        E(x, y, z, r, r*rymul, r, col, seg=seg, ring=ring, fur=fur)
    if paw:
        x, y, z, r = joints[-1]; dy, dz, px, py, pz = paw
        E(x, y+dy, z+dz, px, py, pz, pawcol or col, seg=seg, ring=ring)

