def build_weasel():   # イタチ：しなやかな細長い胴・低い構え・短足・長い尾
    clear()
    FUR=(0.60,0.44,0.28); BELLY=(0.93,0.87,0.74); DK=(0.45,0.32,0.20)
    # 胴＋尾を1本の流れに：背骨に沿って太さを滑らかに変え、深く重ねた楕円で連続面に。
    #   (x, y, z, r, col)  ※rz=r*1.5 で前後を強く重ねて「団子」をやめる
    spine = [
        (0.0, 0.150, -0.66, 0.040, DK ),   # 尾の先（濃い）
        (0.0, 0.142, -0.58, 0.050, DK ),   # 尾
        (0.0, 0.130, -0.50, 0.062, FUR),   # 尾の付け根
        (0.0, 0.122, -0.42, 0.080, FUR),   # 尻
        (0.0, 0.128, -0.34, 0.093, FUR),
        (0.0, 0.133, -0.25, 0.101, FUR),
        (0.0, 0.135, -0.15, 0.104, FUR),
        (0.0, 0.134, -0.05, 0.102, FUR),
        (0.0, 0.132,  0.05, 0.097, FUR),
        (0.0, 0.140,  0.14, 0.090, FUR),   # 肩
        (0.0, 0.165,  0.22, 0.082, FUR),   # 首下
        (0.0, 0.205,  0.30, 0.075, FUR),   # 首（持ち上げ）
        (0.0, 0.245,  0.38, 0.072, FUR),   # 頭の付け根
    ]
    for (x, y, z, r, col) in spine:
        E(x, y, z, r, r*1.02, r*1.5, col, seg=14, ring=10)
    E(0.0,0.092,0.02,0.072,0.050,0.20,BELLY,ring=10)         # 腹の白（前寄り下面・細長）
    # 頭・顔
    E(0.0,0.262,0.43,0.078,0.074,0.090,FUR,ring=11)          # 頭
    E(0.0,0.240,0.52,0.045,0.046,0.072,BELLY,ring=9)         # マズル
    E(0.0,0.240,0.585,0.020,0.018,0.018,(0.15,0.10,0.10),seg=8,ring=6) # 鼻
    eyes(0.295,0.475,sx=0.046,r=0.023,col=(0.05,0.03,0.03))  # 鋭い目（小さめ）
    for s in (-1,1): E(s*0.056,0.340,0.385,0.034,0.040,0.022,FUR,seg=10,ring=8) # 小さい耳
    # 短い四肢（狼と同じ 肩→肢→肉球。イタチは短足なので各段を小さく・低く構える）
    for s in (-1,1):
        # 前脚
        E(s*0.072,0.105,0.155,0.046,0.052,0.050,FUR,seg=11,ring=8)   # 肩(上腕)
        E(s*0.076,0.050,0.175,0.030,0.046,0.034,DK ,seg=10,ring=7)   # 前肢(下腕)
        E(s*0.076,0.014,0.205,0.040,0.022,0.052,DK ,seg=10,ring=7)   # 前足(肉球・前向き)
        # 後脚（「く」の字）
        E(s*0.086,0.110,-0.195,0.058,0.066,0.072,FUR,seg=11,ring=8)  # 腿(ハンチ)
        E(s*0.080,0.052,-0.120,0.030,0.048,0.038,DK ,seg=10,ring=7,rotX=-0.40) # 下腿
        E(s*0.078,0.014,-0.085,0.040,0.022,0.054,DK ,seg=10,ring=7)  # 後足(肉球)
    floor0()

def build_bird():     # 鳥（猛禽）：丸い体＋丸い頭＋かぎ嘴＋翼＋扇尾
    clear()
    BODY=(0.42,0.33,0.25); BELLY=(0.86,0.80,0.70); WING=(0.34,0.26,0.20)
    BEAK=(0.95,0.78,0.22); LEG=(0.92,0.74,0.20); IRIS=(0.98,0.80,0.18)
    E(0.0,0.30,0.0,0.16,0.22,0.15,BODY,ring=12)              # 胴
    E(0.0,0.24,0.12,0.12,0.16,0.08,BELLY,ring=10)            # 胸腹の縞白
    E(0.0,0.55,0.05,0.135,0.13,0.13,BODY,ring=12)            # 頭
    for s in (-1,1): E(s*0.075,0.60,0.07,0.075,0.045,0.03,WING,seg=10,ring=6,rotZ=s*0.5)  # 怒り眉
    eyes(0.565,0.115,sx=0.07,r=0.05,col=IRIS,emis=(0.5,0.4,0.05))   # 鋭い金の目
    E(0.0,0.515,0.165,0.045,0.05,0.06,BEAK,seg=10,ring=7)    # 嘴の根
    E(0.0,0.475,0.175,0.03,0.045,0.045,BEAK,seg=8,ring=6,rotX=0.6) # かぎ先（下向き）
    for s in (-1,1): E(s*0.205,0.32,-0.02,0.07,0.20,0.10,WING,seg=12,ring=9,rotZ=s*0.25,rotX=0.1) # 翼（畳み）
    E(0.0,0.15,-0.18,0.10,0.05,0.17,WING,ring=9)             # 尾羽（扇）
    for s in (-1,1):
        E(s*0.06,0.06,0.05,0.026,0.06,0.03,LEG,seg=8,ring=6) # 脚
        for t in (-1,0,1): E(s*0.06+t*0.018,0.015,0.10,0.012,0.012,0.04,LEG,seg=6,ring=5) # 鉤爪
    floor0()

def build_snake():    # 蛇：連続した胴（背骨カーブに沿って滑らかに細るチューブ）＋持ち上げた頭＋舌
    clear()
    SK=(0.30,0.54,0.28); SK2=(0.25,0.47,0.24); BEL=(0.80,0.82,0.55)  # SK2は薄い帯＝鱗ヒント
    N=30
    for i in range(N):
        t=i/(N-1)
        z=-0.44+t*0.84
        x=math.sin(t*math.pi*2.2)*0.13
        y=0.075+(t**2.6)*0.17                       # 前(頭側)ほど持ち上がる
        r=0.092*(1.0-0.55*abs(t-0.45)/0.55)         # 中央太・両端細の滑らかなテーパ
        col=SK if (i//2)%2==0 else SK2              # 2節ごとの薄い帯（鱗のヒント）
        # rz=r*1.6 で前後を強く重ねて連続面に／fur=法線さざ波で鱗の質感
        E(x,y,z,r,r*0.92,r*1.6,col,seg=14,ring=9,fur=0.004)
    xh=math.sin(1.0*math.pi*2.2)*0.13
    E(xh,0.252,0.43,0.075,0.052,0.10,SK,ring=11,fur=0.004)   # 頭（平たい菱形）
    E(xh,0.228,0.51,0.05,0.035,0.06,BEL,ring=9)              # 顎下の白
    eyes(0.278,0.47,sx=0.045,r=0.024,col=(0.95,0.85,0.15),emis=(0.4,0.35,0.05))  # 黄の目
    ck.whisker((xh,0.228,0.55),(xh-0.03,0.214,0.65),0.006,(0.85,0.10,0.12))      # 舌（二又・チロチロ）
    ck.whisker((xh,0.228,0.55),(xh+0.03,0.214,0.65),0.006,(0.85,0.10,0.12))
    floor0()

def build_wolf():     # 狼：四足・とがり耳・マズル・ふさ尾。一番大きく強そう
    clear()
    FUR=(0.47,0.48,0.52); DK=(0.33,0.34,0.38); BEL=(0.78,0.78,0.80)
    E(0.0,0.36,-0.02,0.16,0.16,0.30,FUR,ring=12)            # 胴
    E(0.0,0.30,-0.05,0.12,0.10,0.24,BEL,ring=10)            # 腹白
    E(0.0,0.40,0.10,0.165,0.16,0.16,DK,ring=11)            # 背の濃い肩
    E(0.0,0.47,0.26,0.12,0.13,0.14,FUR,ring=11)            # 首
    E(0.0,0.52,0.37,0.115,0.115,0.13,FUR,ring=11)         # 頭
    E(0.0,0.485,0.50,0.06,0.06,0.10,FUR,ring=10,fur=0.006) # マズル（毛皮ノイズ）
    E(0.0,0.485,0.575,0.028,0.024,0.028,(0.12,0.12,0.14),seg=8,ring=6) # 鼻
    eyes(0.545,0.47,sx=0.05,r=0.028,col=(0.96,0.62,0.16),emis=(0.55,0.30,0.05)) # 琥珀色の鋭い目（強さ維持）
    for s in (-1,1): E(s*0.075,0.66,0.33,0.05,0.085,0.03,FUR,seg=10,ring=7,rotZ=s*0.18) # とがり耳
    E(0.0,0.345,0.235,0.135,0.125,0.095,FUR,ring=11)       # 胸（前へ張る＝獣らしいシルエット）
    # 脚：肩/肢/肉球の多セグメントで“棒脚”をやめる。前脚=ほぼ直・後脚=「く」の字に曲げる四足姿勢。
    for s in (-1,1):
        # 前脚：肩(上腕・太め前傾)→前肢(下腕・細く垂直)→前足(肉球・前向きに接地)
        E(s*0.100,0.305,0.205,0.064,0.100,0.078,DK ,seg=12,ring=9,rotX=0.10)  # 肩(上腕)
        E(s*0.106,0.150,0.215,0.046,0.115,0.052,FUR,seg=12,ring=9)            # 前肢(下腕)
        E(s*0.106,0.040,0.245,0.058,0.036,0.082,DK ,seg=12,ring=8)            # 前足(肉球)
        # 後脚：腿(ハンチ・後方へ張り出す)→下腿(前下がり)→後足(肉球)＝「く」の字
        E(s*0.122,0.300,-0.130,0.080,0.120,0.108,FUR,seg=12,ring=9)           # 腿(ハンチ)
        E(s*0.113,0.150,-0.050,0.048,0.118,0.058,FUR,seg=12,ring=9,rotX=-0.50)# 下腿(すね)
        E(s*0.110,0.040,0.015,0.058,0.036,0.084,DK ,seg=12,ring=8)            # 後足(肉球)
    for s in (-1,1):   # 肩↔胴・腿↔胴の「つなぎ球」で段差を埋める（継ぎ目消し）
        E(s*0.095,0.300,0.150,0.072,0.090,0.085,FUR,seg=12,ring=9)  # 肩の付け根
        E(s*0.118,0.295,-0.075,0.082,0.095,0.092,FUR,seg=12,ring=9) # 腿の付け根
    E(0.0,0.30,-0.34,0.075,0.085,0.15,FUR,ring=10,fur=0.010) # 尻尾（ふさ・毛皮ノイズ）
    E(0.0,0.27,-0.47,0.06,0.07,0.12,DK,ring=9,fur=0.010)     # 尾の先（毛皮ノイズ）
    floor0()

