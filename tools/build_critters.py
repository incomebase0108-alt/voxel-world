import os, math
import build_pet_chinchilla as ck   # add/ellipsoid/whisker/PARTS/build_glb/render_panel/compose/write_png を流用

E = ck.ellipsoid
def clear(): ck.PARTS.clear()
def floor0():
    miny = min(v[1] for p in ck.PARTS for v in p['verts'])
    for p in ck.PARTS:
        p['verts'] = [(x, y - miny, z) for (x, y, z) in p['verts']]

def eyes(y, z, sx=0.06, r=0.03, col=(0.05,0.04,0.05), emis=None, hi=True):
    for s in (-1, 1):
        E(s*sx, y, z, r, r*1.05, r*0.85, col, seg=12, ring=8, rough=0.2, emis=emis)
        if hi:
            E(s*(sx-0.012), y+0.012, z+0.02, r*0.30, r*0.30, r*0.22, (1,1,1), seg=6, ring=5, rough=0.05, emis=(0.8,0.8,0.8))

