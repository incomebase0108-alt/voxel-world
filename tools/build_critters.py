def build_weasel():   # イタチ：細長く低い体・とがった顔・長い尻尾
    clear()
    FUR=(0.60,0.44,0.28); BELLY=(0.93,0.87,0.74); DK=(0.45,0.32,0.20)
    E(0.0,0.16,-0.05,0.115,0.115,0.30,FUR,ring=11)           # 胴（長い）
    E(0.0,0.17,-0.22,0.12,0.12,0.15,FUR,ring=10)             # 尻
    E(0.0,0.105,0.06,0.075,0.06,0.22,BELLY,ring=9)           # 腹の白
    E(0.0,0.225,0.24,0.085,0.10,0.13,FUR,ring=10)            # 首（持ち上げ）
    E(0.0,0.265,0.39,0.072,0.072,0.10,FUR,ring=10)           # 頭
    E(0.0,0.245,0.49,0.042,0.046,0.07,BELLY,ring=8)          # マズル
    E(0.0,0.245,0.55,0.020,0.018,0.018,(0.15,0.10,0.10),seg=8,ring=6)  # 鼻
    eyes(0.30,0.45,sx=0.046,r=0.024,col=(0.05,0.03,0.03))    # 鋭い目
    for s in (-1,1): E(s*0.058,0.345,0.355,0.034,0.040,0.020,FUR,seg=10,ring=7)  # 小さい耳
    for s in (-1,1):                                          # 短い足
        E(s*0.07,0.05,0.30,0.03,0.05,0.035,DK,seg=8,ring=6)
        E(s*0.08,0.05,-0.16,0.032,0.05,0.04,DK,seg=8,ring=6)
    E(0.0,0.20,-0.36,0.06,0.06,0.13,FUR,ring=8)              # 尻尾
    E(0.0,0.235,-0.50,0.045,0.045,0.13,DK,ring=8)            # 尻尾の先（濃い）
    floor0()

def build_bird():     # 鳥（猛禽）：丸い体＋丸い頭＋かぎ嘴＋翼＋扇尾
    clear()
    BODY=(0.42,0.33,0.25); BELLY=(0.86,0.80,0.70); WING=(0.34,0.26,0.20)
    BEAK=(0.95,0.78,0.22); LEG=(0.92,0.74,0.20); IRIS=(0.98,0.80,0.18)
    E(0.0,0.30,0.0,0.16,0.22,0.15,BODY,ring=12)              # 胴
    E(0.0,0.24,0.12,0.12,0.16,0.08,BELLY,ring=10)            # 胸腹の縞白
    E(0.0,0.55,0.05,0.135,0.13,0.13,BODY,ring=12)            # 頭
    for s in (-1,1): E(s*0.075,0.60,0.07,0.075,0.045,0.03,WING,seg=10,ring=6,rotZ=s*0.5)  # 怒り眉
    eyes(0.565,0.115,sx=0.07,r=0.05,col=IRIS,emis=(0.5,0.4,0.05))   # 鋭い金の目
    E(0.0,0.515,0.165,0.045,0.05,0.06,BEAK,seg=10,ring=7)    # 嘴の根
    E(0.0,0.475,0.175,0.03,0.045,0.045,BEAK,seg=8,ring=6,rotX=0.6) # かぎ先（下向き）
    for s in (-1,1): E(s*0.205,0.32,-0.02,0.07,0.20,0.10,WING,seg=12,ring=9,rotZ=s*0.25,rotX=0.1) # 翼（畳み）
    E(0.0,0.15,-0.18,0.10,0.05,0.17,WING,ring=9)             # 尾羽（扇）
    for s in (-1,1):
        E(s*0.06,0.06,0.05,0.026,0.06,0.03,LEG,seg=8,ring=6) # 脚
        for t in (-1,0,1): E(s*0.06+t*0.018,0.015,0.10,0.012,0.012,0.04,LEG,seg=6,ring=5) # 鉤爪
    floor0()

def build_snake():    # 蛇：S字の胴＋持ち上げた頭＋舌
    clear()
    SK=(0.28,0.52,0.26); SK2=(0.20,0.40,0.20); BEL=(0.80,0.82,0.55)
    N=14
    for i in range(N):
        t=i/(N-1)
        z=-0.42+t*0.78
        x=math.sin(t*math.pi*2.2)*0.13
        y=0.07+ (t**3)*0.16                # 前(頭側)ほど持ち上がる
        r=0.085*(1.0-0.45*t)               # 頭側へ細く…の後、頭で太く
        E(x,y,z,r,r*0.9,r*1.05,SK if i%2 else SK2,seg=12,ring=8)
    xh=math.sin(1.0*math.pi*2.2)*0.13
    E(xh,0.23,0.38,0.075,0.052,0.10,SK,ring=10)              # 頭（平たい菱形）
    E(xh,0.205,0.46,0.05,0.035,0.06,BEL,ring=8)              # 顎下の白
    eyes(0.255,0.42,sx=0.045,r=0.025,col=(0.95,0.85,0.15),emis=(0.4,0.35,0.05))  # 黄の目
    ck.whisker((xh,0.205,0.50),(xh-0.03,0.19,0.60),0.006,(0.85,0.10,0.12))       # 舌（二又）
    ck.whisker((xh,0.205,0.50),(xh+0.03,0.19,0.60),0.006,(0.85,0.10,0.12))
    floor0()

