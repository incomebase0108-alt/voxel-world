def build_weasel():   # イタチ：しなやかな細長い胴・低い構え・短足・長い尾
    clear()
    FUR=(0.60,0.44,0.28); BELLY=(0.93,0.87,0.74); DK=(0.45,0.32,0.20)
    # 胴＋尾を1本の流れに：背骨に沿って太さを滑らかに変え、深く重ねた楕円で連続面に。
    #   (x, y, z, r, col)  ※rz=r*1.5 で前後を強く重ねて「団子」をやめる
    spine = [
        (0.0, 0.150, -0.66, 0.040, DK ),   # 尾の先（濃い）
        (0.0, 0.142, -0.58, 0.050, DK ),   # 尾
        (0.0, 0.130, -0.50, 0.062, FUR),   # 尾の付け根
        (0.0, 0.122, -0.42, 0.080, FUR),   # 尻
        (0.0, 0.128, -0.34, 0.093, FUR),
        (0.0, 0.133, -0.25, 0.101, FUR),
        (0.0, 0.135, -0.15, 0.104, FUR),
        (0.0, 0.134, -0.05, 0.102, FUR),
        (0.0, 0.132,  0.05, 0.097, FUR),
        (0.0, 0.140,  0.14, 0.090, FUR),   # 肩
        (0.0, 0.165,  0.22, 0.082, FUR),   # 首下
        (0.0, 0.205,  0.30, 0.075, FUR),   # 首（持ち上げ）
        (0.0, 0.245,  0.38, 0.072, FUR),   # 頭の付け根
    ]
    for (x, y, z, r, col) in spine:
        E(x, y, z, r, r*1.02, r*1.5, col, seg=14, ring=10)
    E(0.0,0.092,0.02,0.072,0.050,0.20,BELLY,ring=10)         # 腹の白（前寄り下面・細長）
    # 頭・顔
    E(0.0,0.262,0.43,0.078,0.074,0.090,FUR,ring=11)          # 頭
    E(0.0,0.240,0.52,0.045,0.046,0.072,BELLY,ring=9)         # マズル
    E(0.0,0.240,0.585,0.020,0.018,0.018,(0.15,0.10,0.10),seg=8,ring=6) # 鼻
    eyes(0.295,0.475,sx=0.046,r=0.023,col=(0.05,0.03,0.03))  # 鋭い目（小さめ）
    for s in (-1,1): E(s*0.056,0.340,0.385,0.034,0.040,0.022,FUR,seg=10,ring=8) # 小さい耳
    # 短い四肢（狼と同じ 肩→肢→肉球。イタチは短足なので各段を小さく・低く構える）
    for s in (-1,1):
        # 前脚
        E(s*0.072,0.105,0.155,0.046,0.052,0.050,FUR,seg=11,ring=8)   # 肩(上腕)
        E(s*0.076,0.050,0.175,0.030,0.046,0.034,DK ,seg=10,ring=7)   # 前肢(下腕)
        E(s*0.076,0.014,0.205,0.040,0.022,0.052,DK ,seg=10,ring=7)   # 前足(肉球・前向き)
        # 後脚（「く」の字）
        E(s*0.086,0.110,-0.195,0.058,0.066,0.072,FUR,seg=11,ring=8)  # 腿(ハンチ)
        E(s*0.080,0.052,-0.120,0.030,0.048,0.038,DK ,seg=10,ring=7,rotX=-0.40) # 下腿
        E(s*0.078,0.014,-0.085,0.040,0.022,0.054,DK ,seg=10,ring=7)  # 後足(肉球)
    floor0()

def build_bird():     # 猛禽（ワシミミズク系）：丸頭＋羽角＋鋭い目＋かぎ嘴＋羽レイヤー＋カギ爪
    clear()
    BODY=(0.42,0.33,0.25); BELLY=(0.80,0.73,0.62); WING=(0.34,0.26,0.20)
    WING2=(0.26,0.20,0.15); BEAK=(0.18,0.16,0.16); LEG=(0.86,0.70,0.30)
    IRIS=(0.95,0.62,0.12); CLAW=(0.10,0.09,0.09)
    # 胴（丸い・羽の質感）＋胸腹の白
    E(0.0,0.30,0.0,0.16,0.22,0.15,BODY,ring=13,fur=0.006)
    E(0.0,0.24,0.12,0.12,0.17,0.085,BELLY,ring=11,fur=0.006)
    # 頭（大きめ丸）＋うすい顔盤
    E(0.0,0.55,0.05,0.140,0.135,0.135,BODY,ring=13,fur=0.006)
    E(0.0,0.545,0.135,0.120,0.120,0.045,BELLY,ring=11,fur=0.004)
    # 羽角（ear tuft＝ワシミミズクの特徴・外へ跳ねる2段）
    for s in (-1,1):
        E(s*0.088,0.66,-0.01,0.030,0.080,0.030,WING ,seg=8,ring=7,rotZ=s*0.40,rotX=-0.12,fur=0.006)
        E(s*0.088,0.70,-0.01,0.018,0.045,0.020,WING2,seg=7,ring=6,rotZ=s*0.40,rotX=-0.12,fur=0.006)
    # 眉の張り出し羽＝睨む鋭い表情
    for s in (-1,1): E(s*0.072,0.605,0.105,0.060,0.030,0.030,WING,seg=10,ring=6,rotZ=s*0.40)
    # 目：琥珀の虹彩＋黒瞳孔＋小キャッチライト（グロー無し・少し小さく鋭い）
    for s in (-1,1):
        E(s*0.060,0.555,0.140,0.050,0.055,0.040,IRIS,seg=14,ring=10,rough=0.25)            # 虹彩(琥珀)
        E(s*0.060,0.555,0.175,0.026,0.030,0.024,(0.04,0.03,0.03),seg=12,ring=8,rough=0.15) # 瞳孔(黒)
        E(s*0.052,0.572,0.193,0.009,0.009,0.008,(1,1,1),seg=6,ring=5,rough=0.04,emis=(0.7,0.7,0.7)) # キャッチライト
    # かぎ嘴：付け根→上嘴→フック先が下に曲がる（rotXを強めて鉤を明確に）
    E(0.0,0.520,0.150,0.034,0.036,0.040,BEAK,seg=11,ring=8)             # 付け根(cere)
    E(0.0,0.495,0.170,0.028,0.044,0.045,BEAK,seg=10,ring=8,rotX=0.45)   # 上嘴
    E(0.0,0.460,0.176,0.018,0.030,0.030,BEAK,seg=9 ,ring=7,rotX=1.00)   # フック
    E(0.0,0.440,0.166,0.011,0.020,0.018,BEAK,seg=8 ,ring=6,rotX=1.30)   # 鉤先（下向き）
    # 翼（畳み）：主体＋風切羽を数枚レイヤーで段に（板をやめ羽の重なりへ）
    for s in (-1,1):
        E(s*0.178,0.34,-0.02,0.055,0.205,0.105,WING,seg=12,ring=9,rotZ=s*0.20,rotX=0.08,fur=0.006) # 翼主体
        for k,(dy,dz) in enumerate([(0.09,0.03),(0.02,0.0),(-0.05,-0.03),(-0.12,-0.05)]):
            E(s*0.170,0.30+dy,-0.05+dz,0.034,0.150,0.020,WING if k%2 else WING2,
              seg=8,ring=6,rotZ=s*0.16,rotX=0.10,fur=0.006)                                       # 風切羽
    # 尾羽（扇・数枚レイヤーを放射状に）
    for k,ang in enumerate((-0.28,-0.14,0.0,0.14,0.28)):
        E(math.sin(ang)*0.11,0.135,-0.20,0.024,0.040,0.165,WING if k%2 else WING2,
          seg=8,ring=6,rotY=ang,fur=0.006)
    # 脚：太い跗蹠＋前3趾/後1趾＋カギ爪（猛禽の掴む足）
    for s in (-1,1):
        E(s*0.062,0.085,0.04,0.034,0.075,0.036,LEG,seg=11,ring=8)   # 跗蹠(tarsus・太め)
        for (tx,tz) in [(-0.032,0.075),(0.0,0.090),(0.032,0.075),(0.0,-0.050)]:
            E(s*0.062+tx,0.022,0.04+tz,0.016,0.015,0.046,LEG,seg=8,ring=6)                        # 趾
